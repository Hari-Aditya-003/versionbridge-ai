const assert = require('node:assert/strict');
const {initialFlow, reduceFlow} = require('./web/workflow.js');
let s = initialFlow();
s = reduceFlow(s, {event:'project'});
assert.equal(s.nodes.source, 'active');
s = reduceFlow(s, {event:'stage',step:0});
assert.equal(s.nodes.baseline, 'active');
s = reduceFlow(s, {event:'routing',provider:'ollama',attempt:1});
assert.equal(s.backend, 'local');
assert.equal(s.nodes.local, 'active');
s = reduceFlow(s, {event:'diagnosis',provider:'Ollama'});
assert.equal(s.nodes.policy, 'active');
s = reduceFlow(s, {event:'stage',step:2});
assert.equal(s.nodes.verify, 'active');
s = reduceFlow(s, {event:'rejected',verification_tests:{test_x:'failed'}});
assert.equal(s.nodes.verify, 'rejected');
s = reduceFlow(s, {event:'routing',provider:'vultr',attempt:2});
assert.equal(s.nodes.cloud, 'active');
assert.equal(s.nodes.verify, 'pending');
s = reduceFlow(s, {event:'result'});
assert.equal(s.nodes.evidence, 'done');
assert.equal(s.nodes.review, 'active');
assert.equal(s.nodes.local, 'pending');
assert.equal(reduceFlow(initialFlow(),{event:'error',message:'missing report'}).label,'Unverified');
console.log('Workflow state transitions passed');
